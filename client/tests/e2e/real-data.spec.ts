import { expect, test, type Page } from '@playwright/test';
import { createItem, isoDay, newVerifiedUser, uniq } from './helpers';

const DEMO_NAMES = /Priya Sharma|Sarah Khan|Rahul Mehta|Aditi Singh|Unverified Uma|Canon EOS 200D|Acoustic Guitar/;

function watchConsole(page: Page) {
  const problems: string[] = [];
  page.on('pageerror', (e) => problems.push(`pageerror: ${e.message}`));
  page.on('console', (m) => {
    if (m.type() !== 'error') return;
    // Ignore only "the network tunnel is closed" failures: in a sandbox without internet the Google Fonts
    // stylesheet cannot load. Any other console error (404s, JS errors, React warnings) still fails the test.
    if (/ERR_TUNNEL_CONNECTION_FAILED|ERR_INTERNET_DISCONNECTED/.test(m.text())) return;
    problems.push(`console.error: ${m.text()}`);
  });
  return problems;
}

test.describe('A brand-new account sees only real (empty) data', () => {
  test('every page shows its empty state, no fictional content, no console errors', async ({ page }) => {
    const problems = watchConsole(page);
    await newVerifiedUser(page, 'Fresh Face');

    const expectations: [string, RegExp][] = [
      ['/requests/incoming', /No incoming requests yet\./],
      ['/requests/outgoing', /You haven't made any borrowing requests yet\./],
      ['/my-items', /You haven't listed any items yet\./],
      ['/favorites', /Your wish list is empty\./],
      ['/messages', /No conversations yet\./],
      ['/notifications', /You're all caught up!/],
      ['/lending', /You haven't lent out any items yet\./],
      ['/borrowings', /No upcoming borrowings yet\./],
    ];
    for (const [url, text] of expectations) {
      await page.goto(url);
      await expect(page.getByText(text).first(), url).toBeVisible();
      await expect(page.locator('body')).not.toContainText(DEMO_NAMES);
    }

    // No fabricated unread badges anywhere in the shell.
    await page.goto('/dashboard');
    await expect(page.getByRole('button', { name: /notifications, \d+ unread/i })).toHaveCount(0);
    await expect(page.getByLabel(/\d+ new/)).toHaveCount(0);
    await expect(page.locator('body')).not.toContainText(DEMO_NAMES);

    // Public pages on an empty marketplace.
    // (other specs share this database, so search for something that cannot exist rather than assuming it is empty)
    await page.goto('/browse?q=zz-no-such-item-xyzzy');
    await expect(page.getByText(/No items match your search/i).first()).toBeVisible();
    await expect(page.locator('body')).not.toContainText(DEMO_NAMES);

    expect(problems, problems.join('\n')).toEqual([]);
  });

  test('anonymous visitors see no fictional content on public pages', async ({ page }) => {
    const problems = watchConsole(page);
    for (const url of ['/', '/browse', '/about', '/help', '/login', '/signup']) {
      await page.goto(url);
      await expect(page.getByRole('heading', { level: 1 }).first()).toBeVisible();
      await expect(page.locator('body')).not.toContainText(DEMO_NAMES);
    }
    // /auth/me for a signed-out visitor is expected, not an error
    expect(problems.filter((p) => !/401/.test(p)), problems.join('\n')).toEqual([]);
  });
});

test.describe('Real users create real data', () => {
  test('owner declines a real request; borrower sees the decline and a real notification', async ({ browser }) => {
    test.setTimeout(120_000);
    const o = await (await browser.newContext()).newPage();
    const b = await (await browser.newContext()).newPage();
    const problems = watchConsole(o);
    const title = `Ladder ${uniq()}`;
    await newVerifiedUser(o, 'Dana Owner');
    await newVerifiedUser(b, 'Ravi Borrower');
    await createItem(o, title);

    // The owner's "My Items" now shows the real listing (and only that).
    await o.goto('/my-items');
    await expect(o.getByText(title)).toBeVisible();

    await b.goto(`/browse?q=${encodeURIComponent(title)}`);
    await b.getByRole('link', { name: new RegExp(title) }).first().click();
    await b.getByLabel('Start date').fill(isoDay(5));
    await b.getByLabel('End date').fill(isoDay(6));
    await b.getByRole('button', { name: /review request/i }).click();
    await b.getByRole('button', { name: /send request/i }).click();
    await expect(b.getByText(/request sent/i).first()).toBeVisible();

    // Owner: real incoming request + real notification badge, then decline.
    await o.goto('/requests/incoming');
    await expect(o.getByText('Ravi Borrower')).toBeVisible();
    await expect(o.getByText(title)).toBeVisible();
    await o.getByRole('button', { name: /^decline$/i }).click();
    await o.getByRole('dialog').getByRole('button', { name: /decline request/i }).click();
    await expect(o.getByText(/request declined/i).first()).toBeVisible();
    await o.getByRole('tab', { name: /history/i }).click();
    await expect(o.getByText(title)).toBeVisible();

    // Borrower: sees the declined request and a notification generated by that event.
    await b.goto('/requests/outgoing');
    await b.getByRole('tab', { name: /history/i }).click();
    await expect(b.getByText(title)).toBeVisible();
    await expect(b.getByText(/declined/i).first()).toBeVisible();
    await b.goto('/notifications');
    await expect(b.getByText(/declined/i).first()).toBeVisible();
    await expect(b.getByText(/all caught up/i)).toHaveCount(0);

    expect(problems, problems.join('\n')).toEqual([]);
  });
});
